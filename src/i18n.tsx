const dict: Record<Lang, Record<Key, string>> = { vi, en };

type TFn = (key: Key, vars?: Record<string, string | number>) => string;

const I18nContext = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: TFn } | null>(null);

const STORAGE_KEY = 'lang';

function initLang(): Lang {
  const saved = localStorage.getItem(STORAGE_KEY);
  const codes: readonly string[] = LANGS.map((l) => l.code);
  return saved && codes.includes(saved) ? (saved as Lang) : 'vi';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initLang);

  useEffect(() => { document.documentElement.lang = lang; }, [lang]);

  const setLang = (l: Lang) => {
    setLangState(l);
    localStorage.setItem(STORAGE_KEY, l);
  };

  const t: TFn = (key, vars) => {
    // Fallback về tiếng Việt nếu bản dịch mới chưa có chuỗi này → không bao giờ rỗng.
    let s: string = dict[lang][key] ?? dict.vi[key];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };

  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}
